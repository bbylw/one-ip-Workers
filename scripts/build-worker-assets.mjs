/**
 * Embeds the built SPA into the Worker bundle.
 *
 * The deployment is a single Cloudflare Worker without Static Assets, so the
 * Worker has to serve the frontend itself. This script reads `dist/` and writes
 * `public/worker/assets.generated.js`, which `public/worker/static-assets.js`
 * serves at runtime. It runs as the last step of `pnpm build`.
 */
import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, extname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const assetsDir = join(root, "dist");
const outputFile = join(root, "public", "worker", "assets.generated.js");
const entry = "/index.html";

const CONTENT_TYPES = {
  ".css": "text/css; charset=utf-8",
  ".html": "text/html; charset=utf-8",
  ".ico": "image/x-icon",
  ".js": "text/javascript; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".map": "application/json; charset=utf-8",
  ".png": "image/png",
  ".svg": "image/svg+xml",
  ".txt": "text/plain; charset=utf-8",
  ".webmanifest": "application/manifest+json",
  ".webp": "image/webp",
  ".woff2": "font/woff2",
};

// Hosting configuration for the Static Assets product. The equivalent headers
// live in `public/worker/static-assets.js`, so these files are never served.
const CONFIG_FILES = new Set(["/_headers", "/_redirects"]);

async function collect(directory, prefix = "") {
  const files = [];
  for (const item of await readdir(directory, { withFileTypes: true })) {
    const path = `${prefix}/${item.name}`;
    if (item.isDirectory()) {
      // Backend source, removed from `dist` by the Vite build.
      if (path === "/worker") continue;
      files.push(...(await collect(join(directory, item.name), path)));
    } else if (item.isFile() && !CONFIG_FILES.has(path)) {
      files.push({ path, file: join(directory, item.name) });
    }
  }
  return files;
}

if (!existsSync(assetsDir))
  throw new Error(
    "dist/ not found. Run `vite build` (or `pnpm build`) before embedding the SPA in the Worker.",
  );

const files = (await collect(assetsDir)).sort((a, b) =>
  a.path < b.path ? -1 : 1,
);
const records = [];
let embedded = 0;

for (const { path, file } of files) {
  const body = await readFile(file);
  embedded += body.byteLength;
  const extension = extname(path).toLowerCase();
  records.push([
    path,
    {
      t: CONTENT_TYPES[extension] ?? "application/octet-stream",
      // Content hash keeps conditional requests working without caching bodies.
      h: `"${createHash("sha256").update(body).digest("hex").slice(0, 32)}"`,
      d: body.toString("base64"),
    },
  ]);
}

if (!records.some(([path]) => path === entry))
  throw new Error(`${entry} is missing from dist/. Run a full \`pnpm build\`.`);

const manifest = records
  .map(
    ([path, record]) =>
      `  ${JSON.stringify(path)}: { t: ${JSON.stringify(record.t)}, h: ${JSON.stringify(record.h)}, d: ${JSON.stringify(record.d)} },`,
  )
  .join("\n");

const source = `// AUTO-GENERATED by scripts/build-worker-assets.mjs — do not edit.
// Packed from dist/ at ${new Date().toISOString()}. Rebuild with \`pnpm build\`.
export const assetBuild = ${JSON.stringify(new Date().toISOString())};
export const assetEntry = ${JSON.stringify(entry)};
export const assets = {
${manifest}
};
`;

await writeFile(outputFile, source);

const relativeOutput = relative(root, outputFile).split(sep).join("/");
console.log(
  `Embedded ${records.length} files (${(embedded / 1024).toFixed(0)} KiB) into ${relativeOutput} (${(source.length / 1024).toFixed(0)} KiB)`,
);
